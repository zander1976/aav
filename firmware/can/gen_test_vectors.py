#!/usr/bin/env python3
"""
Regenerate the CAN test vectors from the Python codec.

Writes:
  firmware/can/test_vectors.json                       (read by aav_spine's tests)
  firmware/spine/crates/spine-core/tests/vectors.rs    (read by `cargo test`)

Run it after any change to aav.dbc and can_codec.py:
  python3 firmware/can/gen_test_vectors.py
"""

import importlib.util
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
CODEC = ROOT / 'src/backends/aav_spine/aav_spine/can_codec.py'
JSON_OUT = ROOT / 'firmware/can/test_vectors.json'
RUST_OUT = ROOT / 'firmware/spine/crates/spine-core/tests/vectors.rs'
DBC = ROOT / 'firmware/can/aav.dbc'
DBC_VERSION = re.search(r'^VERSION "([^"]+)"', DBC.read_text(), re.M).group(1)

spec = importlib.util.spec_from_file_location('can_codec', CODEC)
codec = importlib.util.module_from_spec(spec)
sys.modules['can_codec'] = codec  # dataclasses look the module up while loading
spec.loader.exec_module(codec)

# (case name, frame id, physical values). Avoid values that land exactly on .5 of a bit.
CASES = [
    ('estop_on', codec.ESTOP_CMD_ID, {'estop_request': 1, 'counter': 3}),
    ('estop_off', codec.ESTOP_CMD_ID, {'estop_request': 0, 'counter': 15}),
    ('drive_forward_left', codec.DRIVE_CMD_ID, {
        'target_speed': 1.5, 'steering_angle': 0.25, 'accel_limit': 1.0,
        'steer_rate_limit': 0.5, 'armed': 1, 'counter': 7}),
    ('drive_reverse_right', codec.DRIVE_CMD_ID, {
        'target_speed': -0.75, 'steering_angle': -0.4363, 'accel_limit': 0.0,
        'steer_rate_limit': 0.0, 'armed': 0, 'counter': 0}),
    ('drive_saturates', codec.DRIVE_CMD_ID, {
        'target_speed': 40.0, 'steering_angle': -5.0, 'accel_limit': 20.0,
        'steer_rate_limit': 9.0, 'armed': 1, 'counter': 15}),
    ('feedback_moving', codec.VEHICLE_FEEDBACK_ID, {
        'measured_speed': 2.345, 'measured_steering_angle': -0.1,
        'wheel_ticks': 65535, 'counter': 9}),
    ('feedback_reverse', codec.VEHICLE_FEEDBACK_ID, {
        'measured_speed': -0.4, 'measured_steering_angle': 0.3,
        'wheel_ticks': 1234, 'counter': 1}),
    ('status_computer', codec.VEHICLE_STATUS_ID, {
        'mode': codec.MODE_COMPUTER, 'armed': 1, 'estop_active': 0,
        'throttle': 37.5, 'brake': 0.0, 'faults': 0x0081, 'counter': 12}),
    ('status_rc_estop', codec.VEHICLE_STATUS_ID, {
        'mode': codec.MODE_RC, 'armed': 0, 'estop_active': 1,
        'throttle': 0.0, 'brake': 100.0, 'faults': 0x0100, 'counter': 4}),
    ('wheel_left_forward', codec.WHEEL_SPEED_L_ID, {
        'wheel_speed': 2.718, 'pulse_count': 40000, 'direction_known': 0, 'counter': 5}),
    ('wheel_right_reverse', codec.WHEEL_SPEED_R_ID, {
        'wheel_speed': -0.333, 'pulse_count': 65535, 'direction_known': 1, 'counter': 14}),
    ('wheel_right_stopped', codec.WHEEL_SPEED_R_ID, {
        'wheel_speed': 0.0, 'pulse_count': 0, 'direction_known': 0, 'counter': 0}),
]

RUST_TYPES = {
    codec.ESTOP_CMD_ID: 'EstopCmd',
    codec.DRIVE_CMD_ID: 'DriveCmd',
    codec.VEHICLE_FEEDBACK_ID: 'VehicleFeedback',
    codec.VEHICLE_STATUS_ID: 'VehicleStatus',
    codec.WHEEL_SPEED_L_ID: 'WheelSpeed',
    codec.WHEEL_SPEED_R_ID: 'WheelSpeed',
}
# The wheel frames share a type; the wheel picks the ID, so it is a field, not a signal.
WHEELS = {codec.WHEEL_SPEED_L_ID: 'Wheel::Left', codec.WHEEL_SPEED_R_ID: 'Wheel::Right'}
BOOL_FIELDS = {'estop_request', 'armed', 'estop_active', 'direction_known'}
INT_FIELDS = {'counter': 'u8', 'wheel_ticks': 'u16', 'faults': 'u16', 'pulse_count': 'u16'}
MODES = {0: 'Mode::Manual', 1: 'Mode::Rc', 2: 'Mode::Computer'}


def rust_value(name, value):
    if name in BOOL_FIELDS:
        return 'true' if value else 'false'
    if name == 'mode':
        return MODES[int(value)]
    if name in INT_FIELDS:
        return str(int(value))
    return repr(float(value)) + '_f32'


def main():
    vectors = []
    rust = [
        '// Generated by firmware/can/gen_test_vectors.py from the Python codec. Do not edit.',
        '// Checks that the Rust firmware and the ROS bridge put the same bytes on the bus.',
        '',
        'use spine_core::protocol::*;',
        '',
        'fn close(a: f32, b: f32) -> bool {',
        '    (a - b).abs() < 1e-4',
        '}',
    ]
    for name, can_id, values in CASES:
        data = codec.pack(can_id, values)
        decoded = codec.unpack(can_id, data)
        vectors.append({
            'name': name,
            'id': can_id,
            'frame': codec.FRAMES[can_id].name,
            'values': values,
            'decoded': decoded,
            'data_hex': data.hex(),
        })
        ty = RUST_TYPES[can_id]
        bytes_lit = ', '.join(f'0x{b:02x}' for b in data)
        fields = ', '.join(f'{k}: {rust_value(k, values.get(k, 0))}' for k in decoded)
        wheel = WHEELS.get(can_id)
        if wheel:
            fields = f'wheel: {wheel}, {fields}'
        decode_args = f'{wheel}, ' if wheel else ''
        checks = []
        for k, v in decoded.items():
            if k in BOOL_FIELDS:
                checks.append(f'    assert!({"" if v else "!"}back.{k});')
            elif k == 'mode' or k in INT_FIELDS:
                checks.append(f'    assert_eq!(back.{k}, {rust_value(k, v)});')
            else:
                checks.append(f'    assert!(close(back.{k}, {rust_value(k, v)}), "{k}");')
        rust += [
            '',
            '#[test]',
            f'fn {name}() {{',
            f'    let msg = {ty} {{ {fields} }};',
            f'    assert_eq!(msg.encode(), [{bytes_lit}]);',
            f'    let back = {ty}::decode({decode_args}&[{bytes_lit}]).unwrap();',
            *checks,
            '}',
        ]
    JSON_OUT.write_text(json.dumps({
        'dbc_version': DBC_VERSION,
        'generated_by': 'firmware/can/gen_test_vectors.py',
        'vectors': vectors,
    }, indent=2) + '\n')
    RUST_OUT.parent.mkdir(parents=True, exist_ok=True)
    RUST_OUT.write_text('\n'.join(rust) + '\n')
    # Format it the way `cargo fmt` would, so `cargo fmt --check` stays clean.
    rustfmt = shutil.which('rustfmt')
    if rustfmt:
        subprocess.run([rustfmt, '--edition', '2021', str(RUST_OUT)], check=True)
    print(f'wrote {len(vectors)} vectors to {JSON_OUT.relative_to(ROOT)} and '
          f'{RUST_OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
